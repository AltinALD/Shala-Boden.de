let currentLang = localStorage.getItem("shala-lang") || "de";
if (currentLang !== "de" && currentLang !== "en") currentLang = "de";

function applyTranslations(lang) {
  const dict = translations[lang] || translations.de;
  document.documentElement.lang = lang;
  document.title =
    lang === "en"
      ? "SHALA — Floor coatings in Heilbronn"
      : "SHALA — Bodenbeschichtung in Heilbronn";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key]) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (dict[key]) el.setAttribute("aria-label", dict[key]);
  });

  const fab = document.getElementById("callFab");
  if (fab) fab.setAttribute("aria-label", lang === "en" ? "Call SHALA" : "SHALA anrufen");

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  currentLang = lang;
  localStorage.setItem("shala-lang", lang);

  const cap = document.getElementById("lbCap");
  const lightbox = document.getElementById("lightbox");
  if (cap && lightbox && !lightbox.hidden && typeof lightboxIndex === "number") {
    const shot = shots[lightboxIndex];
    if (shot) cap.textContent = shot.querySelector(".shot-cap").textContent;
  }
}

function initLang() {
  applyTranslations(currentLang);
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => applyTranslations(btn.dataset.lang));
  });
}

function initNav() {
  const toggle = document.getElementById("navToggle");
  const nav = document.getElementById("nav");
  if (!toggle || !nav) return;

  const close = () => {
    nav.classList.remove("is-open");
    toggle.setAttribute("aria-expanded", "false");
  };

  toggle.addEventListener("click", () => {
    const open = nav.classList.toggle("is-open");
    toggle.setAttribute("aria-expanded", String(open));
  });

  nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", close));
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") close();
  });
}

function initHeader() {
  const header = document.querySelector(".site-header");
  const bar = document.getElementById("scrollProgress");
  if (!header) return;

  const onScroll = () => {
    header.classList.toggle("is-scrolled", window.scrollY > 24);
    if (bar) {
      const max = document.documentElement.scrollHeight - window.innerHeight;
      bar.style.width = `${max > 0 ? (window.scrollY / max) * 100 : 0}%`;
    }
  };

  onScroll();
  window.addEventListener("scroll", onScroll, { passive: true });
}

function initForm() {
  const form = document.getElementById("contactForm");
  const success = document.getElementById("formSuccess");
  if (!form) return;

  form.addEventListener("submit", (e) => {
    e.preventDefault();
    const name = form.name;
    const email = form.email;
    const phone = form.phone;
    const city = form.city;
    const service = form.service;
    const message = form.message;

    [name, email, message].forEach((field) => field.classList.remove("is-invalid"));

    let valid = true;
    if (!name.value.trim()) {
      name.classList.add("is-invalid");
      valid = false;
    }
    if (!email.value.trim() || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.value)) {
      email.classList.add("is-invalid");
      valid = false;
    }
    if (!message.value.trim()) {
      message.classList.add("is-invalid");
      valid = false;
    }
    if (!valid) {
      const first = form.querySelector(".is-invalid");
      if (first) first.focus();
      return;
    }

    const serviceLabel = service.options[service.selectedIndex].text;
    const en = currentLang === "en";
    const subject = en
      ? `SHALA inquiry — ${serviceLabel}`
      : `Anfrage SHALA — ${serviceLabel}`;
    const body = [
      en ? "Hello," : "Guten Tag,",
      "",
      `Name: ${name.value.trim()}`,
      `E-Mail: ${email.value.trim()}`,
      `${en ? "Phone" : "Telefon"}: ${phone.value.trim() || "–"}`,
      `${en ? "Place" : "Ort"}: ${city.value.trim() || "–"}`,
      `${en ? "Service" : "Leistung"}: ${serviceLabel}`,
      "",
      message.value.trim(),
    ].join("\n");

    success.hidden = false;
    window.location.href = `mailto:shalamustaf90@gmail.com?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
    form.reset();
  });
}

function initPreloader() {
  const preloader = document.getElementById("preloader");
  const fill = document.getElementById("preloaderFill");
  const pct = document.getElementById("preloaderPct");
  if (!preloader || !fill || !pct) {
    document.body.classList.remove("is-loading");
    return;
  }

  const minTime = 1400;
  const started = performance.now();
  let progress = 0;
  let finished = false;

  const tick = setInterval(() => {
    if (finished) return;
    progress = Math.min(progress + Math.random() * 14 + 4, 92);
    fill.style.width = `${progress}%`;
    fill.parentElement.setAttribute("aria-valuenow", String(Math.round(progress)));
    pct.textContent = `${Math.round(progress)}%`;
  }, 110);

  const finish = () => {
    if (finished) return;
    finished = true;
    clearInterval(tick);
    const wait = Math.max(0, minTime - (performance.now() - started));
    setTimeout(() => {
      fill.style.width = "100%";
      fill.parentElement.setAttribute("aria-valuenow", "100");
      pct.textContent = "100%";
      setTimeout(() => {
        preloader.classList.add("is-done");
        preloader.setAttribute("aria-busy", "false");
        document.body.classList.remove("is-loading");
        setTimeout(() => preloader.remove(), 700);
      }, 220);
    }, wait);
  };

  if (document.readyState === "complete") finish();
  else window.addEventListener("load", finish, { once: true });
}

